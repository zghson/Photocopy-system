-- [SEG] Bảng CUSTOMERS – khách hàng đặt in
CREATE TABLE customers (
  customer_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_code  VARCHAR2(20)  NOT NULL,
  customer_name  VARCHAR2(150) NOT NULL,
  customer_type  VARCHAR2(12)  DEFAULT 'CORPORATE' NOT NULL,
  tax_code       VARCHAR2(14),
  email          VARCHAR2(120),
  phone          VARCHAR2(15),
  address        VARCHAR2(250),
  brand_profile  JSON,
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_customers        PRIMARY KEY (customer_id),
  CONSTRAINT uq_customers_code   UNIQUE (customer_code),
  CONSTRAINT ck_customers_type   CHECK (customer_type IN ('CORPORATE','INDIVIDUAL')),
  CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE','INACTIVE')),
  CONSTRAINT ck_customers_email  CHECK (email IS NULL OR
      REGEXP_LIKE(email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
  CONSTRAINT ck_customers_phone  CHECK (phone IS NULL OR REGEXP_LIKE(phone, '^[0-9+]{9,15}$')),
  CONSTRAINT ck_customers_tax    CHECK (tax_code IS NULL OR
      REGEXP_LIKE(tax_code, '^[0-9]{10}(-[0-9]{3})?$'))
);

-- [SEG] Bảng BANK_ACCOUNTS – tài khoản nhận tiền của khách hàng (đích của VietQR)
CREATE TABLE bank_accounts (
  account_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id   NUMBER        NOT NULL,
  bank_bin      VARCHAR2(6)   NOT NULL,
  bank_name     VARCHAR2(80)  NOT NULL,
  account_no    VARCHAR2(19)  NOT NULL,
  account_name  VARCHAR2(100) NOT NULL,
  is_default    NUMBER(1)     DEFAULT 0 NOT NULL,
  status        VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT pk_bank_accounts  PRIMARY KEY (account_id),
  CONSTRAINT fk_bank_customer  FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT uq_bank_account   UNIQUE (bank_bin, account_no),
  CONSTRAINT ck_bank_bin       CHECK (REGEXP_LIKE(bank_bin, '^[0-9]{6}$')),
  CONSTRAINT ck_bank_accno     CHECK (REGEXP_LIKE(account_no, '^[0-9A-Za-z]{1,19}$')),
  CONSTRAINT ck_bank_default   CHECK (is_default IN (0, 1)),
  CONSTRAINT ck_bank_status    CHECK (status IN ('ACTIVE','INACTIVE'))
);

-- [SEG] Bảng EMPLOYEES – nhân viên vận hành, thiết kế, kiểm tra chất lượng
CREATE TABLE employees (

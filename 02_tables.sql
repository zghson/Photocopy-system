  employee_code  VARCHAR2(20)  NOT NULL,
  full_name      VARCHAR2(100) NOT NULL,
  role           VARCHAR2(12)  DEFAULT 'OPERATOR' NOT NULL,
  hire_date      DATE,
  phone          VARCHAR2(15),
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT pk_employees       PRIMARY KEY (employee_id),
  CONSTRAINT uq_employees_code  UNIQUE (employee_code),
  CONSTRAINT ck_employees_role  CHECK (role IN ('OPERATOR','DESIGNER','QC','MANAGER')),
  CONSTRAINT ck_employees_phone CHECK (phone IS NULL OR REGEXP_LIKE(phone, '^[0-9+]{9,15}$')),
  CONSTRAINT ck_employees_stat  CHECK (status IN ('ACTIVE','INACTIVE'))
);

-- [SEG] Bảng MACHINES – máy in tốc độ cao
CREATE TABLE machines (
  machine_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  machine_code  VARCHAR2(20)  NOT NULL,
  machine_name  VARCHAR2(100) NOT NULL,
  machine_type  VARCHAR2(15)  NOT NULL,
  speed_ppm     NUMBER(6)     NOT NULL,
  status        VARCHAR2(12)  DEFAULT 'IDLE' NOT NULL,
  install_date  DATE,
  spec          JSON,
  CONSTRAINT pk_machines      PRIMARY KEY (machine_id),
  CONSTRAINT uq_machines_code UNIQUE (machine_code),
  CONSTRAINT ck_machines_type CHECK (machine_type IN ('INKJET','LASER','DIGITAL_PRESS')),
  CONSTRAINT ck_machines_spd  CHECK (speed_ppm > 0),
  CONSTRAINT ck_machines_stat CHECK (status IN ('IDLE','BUSY','MAINTENANCE'))
);

-- [SEG] Bảng PRODUCTS – danh mục sản phẩm in (có cột VECTOR phục vụ gợi ý ngữ nghĩa)
CREATE TABLE products (
  product_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  product_code       VARCHAR2(20)  NOT NULL,
  product_name       VARCHAR2(150) NOT NULL,
  category           VARCHAR2(15)  NOT NULL,
  description        VARCHAR2(500),
  unit_price         NUMBER(12,2)  DEFAULT 0 NOT NULL,
  spec               JSON,
  product_embedding  VECTOR(384, FLOAT32),
  is_active          NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_products       PRIMARY KEY (product_id),
  CONSTRAINT uq_products_code  UNIQUE (product_code),
  CONSTRAINT ck_products_cat   CHECK (category IN ('INVOICE','INVITATION','MEMBER_CARD','VOUCHER','LABEL')),
  CONSTRAINT ck_products_price CHECK (unit_price >= 0),
  CONSTRAINT ck_products_act   CHECK (is_active IN (0, 1))
);

-- [SEG] Bảng TEMPLATES – mẫu in cá nhân hóa (layout JSON + embedding VECTOR)
CREATE TABLE templates (
  template_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  customer_id         NUMBER         NOT NULL,
  product_id          NUMBER         NOT NULL,
  template_name       VARCHAR2(150)  NOT NULL,
  description         VARCHAR2(1000),
  layout              JSON           NOT NULL,
  template_embedding  VECTOR(384, FLOAT32),
  version             NUMBER(3)      DEFAULT 1 NOT NULL,
  created_at          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_templates       PRIMARY KEY (template_id),
  CONSTRAINT fk_tpl_customer    FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT fk_tpl_product     FOREIGN KEY (product_id)  REFERENCES products (product_id),
  CONSTRAINT uq_tpl_version     UNIQUE (customer_id, template_name, version)
);

-- [SEG] Bảng ORDERS – đơn đặt in
CREATE TABLE orders (
  order_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  order_code    VARCHAR2(20)  NOT NULL,
  customer_id   NUMBER        NOT NULL,
  order_date    DATE          DEFAULT SYSDATE NOT NULL,
  due_date      DATE,
  status        VARCHAR2(14)  DEFAULT 'NEW' NOT NULL,
  total_amount  NUMBER(15,2)  DEFAULT 0 NOT NULL,
  note          VARCHAR2(300),
  CONSTRAINT pk_orders        PRIMARY KEY (order_id),
  CONSTRAINT uq_orders_code   UNIQUE (order_code),
  CONSTRAINT fk_orders_cust   FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT ck_orders_status CHECK (status IN ('NEW','CONFIRMED','IN_PRODUCTION','COMPLETED','CANCELLED')),
  CONSTRAINT ck_orders_total  CHECK (total_amount >= 0),
  CONSTRAINT ck_orders_due    CHECK (due_date IS NULL OR due_date >= TRUNC(order_date))
);

-- [SEG] Bảng PRINT_JOBS – lệnh in gắn với máy in và nhân viên vận hành
CREATE TABLE print_jobs (
  job_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  job_code       VARCHAR2(20) NOT NULL,
  order_id       NUMBER       NOT NULL,
  template_id    NUMBER       NOT NULL,
  machine_id     NUMBER,
  operator_id    NUMBER,
  quantity       NUMBER(9)    NOT NULL,
  printed_count  NUMBER(9)    DEFAULT 0 NOT NULL,
  failed_count   NUMBER(9)    DEFAULT 0 NOT NULL,
  status         VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
  priority       NUMBER(1)    DEFAULT 3 NOT NULL,
  started_at     TIMESTAMP,
  finished_at    TIMESTAMP,
  job_config     JSON,
  CONSTRAINT pk_print_jobs     PRIMARY KEY (job_id),
  CONSTRAINT uq_jobs_code      UNIQUE (job_code),
  CONSTRAINT fk_jobs_order     FOREIGN KEY (order_id)    REFERENCES orders (order_id),
  CONSTRAINT fk_jobs_template  FOREIGN KEY (template_id) REFERENCES templates (template_id),
  CONSTRAINT fk_jobs_machine   FOREIGN KEY (machine_id)  REFERENCES machines (machine_id),
  CONSTRAINT fk_jobs_operator  FOREIGN KEY (operator_id) REFERENCES employees (employee_id),
  CONSTRAINT ck_jobs_qty       CHECK (quantity > 0),
  CONSTRAINT ck_jobs_counts    CHECK (printed_count >= 0 AND failed_count >= 0
                                      AND printed_count + failed_count <= quantity),
  CONSTRAINT ck_jobs_status    CHECK (status IN ('PENDING','QUEUED','PRINTING','PAUSED','COMPLETED','FAILED')),
  CONSTRAINT ck_jobs_priority  CHECK (priority BETWEEN 1 AND 5),
  CONSTRAINT ck_jobs_time      CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);

-- [SEG] Bảng PRINT_RECORDS – dữ liệu cá nhân hóa của từng tờ in (cột JSON + JSON Schema)
CREATE TABLE print_records (
  record_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  job_id          NUMBER        NOT NULL,
  seq_no          NUMBER(9)     NOT NULL,
  recipient_name  VARCHAR2(150) NOT NULL,
  amount          NUMBER(15,0)  DEFAULT 0 NOT NULL,
  variable_data   JSON          NOT NULL,
  print_status    VARCHAR2(8)   DEFAULT 'WAITING' NOT NULL,
  printed_at      TIMESTAMP,
  CONSTRAINT pk_print_records   PRIMARY KEY (record_id),
  CONSTRAINT fk_rec_job         FOREIGN KEY (job_id) REFERENCES print_jobs (job_id) ON DELETE CASCADE,
  CONSTRAINT uq_rec_job_seq     UNIQUE (job_id, seq_no),
  CONSTRAINT ck_rec_amount      CHECK (amount >= 0),
  CONSTRAINT ck_rec_status      CHECK (print_status IN ('WAITING','PRINTED','FAILED')),
  CONSTRAINT ck_rec_json        CHECK (variable_data IS JSON VALIDATE
    '{"type":"object",
      "properties":{"full_name":{"type":"string","minLength":1},
                    "total":{"type":"number","minimum":0}},
      "required":["full_name","total"]}')
);

-- [SEG] Bảng VIETQR_CODES – mã VietQR động, mỗi bản ghi in một mã
CREATE TABLE vietqr_codes (
  qr_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  record_id   NUMBER         NOT NULL,
  account_id  NUMBER         NOT NULL,
  qr_ref      VARCHAR2(25)   NOT NULL,
  amount      NUMBER(15,0)   DEFAULT 0 NOT NULL,
  add_info    VARCHAR2(25)   NOT NULL,
  qr_payload  VARCHAR2(512)  NOT NULL,
  crc         VARCHAR2(4)    NOT NULL,
  status      VARCHAR2(10)   DEFAULT 'ACTIVE' NOT NULL,
  created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  expired_at  TIMESTAMP      NOT NULL,
  paid_at     TIMESTAMP,
  CONSTRAINT pk_vietqr_codes  PRIMARY KEY (qr_id),
  CONSTRAINT fk_qr_record     FOREIGN KEY (record_id)  REFERENCES print_records (record_id) ON DELETE CASCADE,
  CONSTRAINT fk_qr_account    FOREIGN KEY (account_id) REFERENCES bank_accounts (account_id),
  CONSTRAINT uq_qr_record     UNIQUE (record_id),
  CONSTRAINT uq_qr_ref        UNIQUE (qr_ref),
  CONSTRAINT ck_qr_amount     CHECK (amount >= 0),
  CONSTRAINT ck_qr_crc        CHECK (REGEXP_LIKE(crc, '^[0-9A-F]{4}$')),
  CONSTRAINT ck_qr_status     CHECK (status IN ('ACTIVE','PAID','EXPIRED','CANCELLED')),
  CONSTRAINT ck_qr_paid       CHECK (status <> 'PAID' OR paid_at IS NOT NULL)
);

-- [SEG] Bảng PAYMENTS – giao dịch ngân hàng nhận về qua webhook
CREATE TABLE payments (
  payment_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  qr_id             NUMBER,
  bank_txn_ref      VARCHAR2(40)  NOT NULL,
  paid_amount       NUMBER(15,0)  NOT NULL,
  paid_at           TIMESTAMP     NOT NULL,
  payer_name        VARCHAR2(100),
  transfer_content  VARCHAR2(250),
  match_status      VARCHAR2(12)  NOT NULL,
  raw_payload       JSON,
  received_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_payments      PRIMARY KEY (payment_id),
  CONSTRAINT uq_pay_txn       UNIQUE (bank_txn_ref),
  CONSTRAINT fk_pay_qr        FOREIGN KEY (qr_id) REFERENCES vietqr_codes (qr_id),
  CONSTRAINT ck_pay_amount    CHECK (paid_amount > 0),
  CONSTRAINT ck_pay_match     CHECK (match_status IN ('MATCHED','AMOUNT_DIFF','UNMATCHED','DUPLICATE'))
);

-- [SEG] Bảng JOB_LOGS – nhật ký đổi trạng thái lệnh in (do trigger ghi)
CREATE TABLE job_logs (
  log_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  job_id      NUMBER        NOT NULL,
  old_status  VARCHAR2(10),
  new_status  VARCHAR2(10),
  changed_by  VARCHAR2(60)  DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  changed_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  message     VARCHAR2(300),
  CONSTRAINT pk_job_logs  PRIMARY KEY (log_id),
  CONSTRAINT fk_log_job   FOREIGN KEY (job_id) REFERENCES print_jobs (job_id) ON DELETE CASCADE
);

